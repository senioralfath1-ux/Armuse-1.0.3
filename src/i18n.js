  let current = document.documentElement.getAttribute('lang') || 'id';
  if (!DICT[current]) current = 'id';

  function t(key, params) {
    let str = (DICT[current] && DICT[current][key]) || (DICT.id && DICT.id[key]) || key;
    if (params && typeof params === 'object') {
      for (const k of Object.keys(params)) {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k]);
      }
    }
    return str;
  }

  function apply() {
    document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', t(el.dataset.i18nPh)); });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const v = t(el.dataset.i18nAria);
      el.setAttribute('aria-label', v);
      if (el.hasAttribute('title')) el.setAttribute('title', v);
    });
  }

  function setLang(lang) {
    if (!DICT[lang]) return;
    current = lang;
    document.documentElement.setAttribute('lang', lang);
    apply();
  }

  
  function formatCount(count, kind) {
    const n = Number(count) || 0;
    if (current === 'id') {
      const w = {
        song: 'lagu',
        album: 'album',
        artist: 'artis',
        playlist: 'playlist'
      }[kind] || kind;
      return n + ' ' + w;
    }
    if (current === 'ja') {
      const w = {
        song: '曲',
        album: 'アルバム',
        artist: 'アーティスト',
        playlist: 'プレイリスト'
      }[kind] || kind;
      return n + w;
    }
    // en (default)
    const isOne = n === 1;
    const w = {
      song: isOne ? 'song' : 'songs',
      album: isOne ? 'album' : 'albums',
      artist: isOne ? 'artist' : 'artists',
      playlist: isOne ? 'playlist' : 'playlists'
    }[kind] || kind;
    return n + ' ' + w;
  }

  RD.i18n = { t, apply, setLang, getLang: () => current, formatCount };
